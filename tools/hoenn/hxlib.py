"""Shared helpers for the Emerald -> FireRed (Hoenn) porting tools."""
import json, os, re, collections

FR = os.environ.get("FR", "/home/claude/pokefirered")
EM = os.environ.get("EM", "/home/claude/pokeemerald")
STATE_PATH = os.path.join(FR, "tools/hoenn/state.json")


def read(p):
    with open(p, errors="ignore") as f:
        return f.read()


def write(p, s):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f:
        f.write(s)


# ----------------------------------------------------------------------------
# persistent allocation state (flags, trainers, vars)
# ----------------------------------------------------------------------------
FLAG_POOL = (list(range(0x300, 0x3D8)) + list(range(0xAF, 0x154)) + list(range(0x4BD, 0x500)))
HIDDEN_ITEM_FLAG_IDS = [0x07, 0x10, 0x28, 0x2B, 0x2C, 0x2D, 0x2E, 0x7C]  # FLAG_HIDDEN_ITEMS_START + n
VAR_POOL = []  # filled lazily from vars.h


class State:
    def __init__(self):
        if os.path.exists(STATE_PATH):
            d = json.load(open(STATE_PATH))
        else:
            d = {}
        self.flags = d.get("flags", {})
        self.hidden = d.get("hidden", {})
        self.trainers = d.get("trainers", {})
        self.vars = d.get("vars", {})
        self.mapsecs = d.get("mapsecs", {})

    def save(self):
        json.dump({"flags": self.flags, "hidden": self.hidden, "trainers": self.trainers,
                   "vars": self.vars, "mapsecs": self.mapsecs},
                  open(STATE_PATH, "w"), indent=1, sort_keys=True)

    # flags ------------------------------------------------------------------
    def flag(self, emerald_name):
        n = "FLAG_HX_" + emerald_name[len("FLAG_"):]
        if n not in self.flags:
            used = set(self.flags.values())
            for v in FLAG_POOL:
                if v not in used:
                    self.flags[n] = v
                    break
            else:
                raise SystemExit("out of flags")
        return n

    def hidden_flag(self, emerald_name):
        n = "FLAG_HX_" + emerald_name[len("FLAG_"):]
        if n not in self.hidden:
            used = set(self.hidden.values())
            for v in HIDDEN_ITEM_FLAG_IDS:
                if v not in used:
                    self.hidden[n] = v
                    break
            else:
                raise SystemExit("out of hidden-item flags")
        return n

    def var(self, emerald_name):
        if emerald_name.startswith("VAR_TEMP_"):
            return emerald_name
        n = "VAR_HX_" + emerald_name[len("VAR_"):]
        if n not in self.vars:
            pool = free_vars()
            used = set(self.vars.values())
            for v in pool:
                if v not in used:
                    self.vars[n] = v
                    break
            else:
                raise SystemExit("out of vars")
        return n

    def write_headers(self):
        out = ["// Auto-generated by tools/hoenn -- do not edit\n#ifndef GUARD_CONSTANTS_HX_FLAGS_H\n#define GUARD_CONSTANTS_HX_FLAGS_H\n\n"]
        for n, v in sorted(self.flags.items(), key=lambda kv: kv[1]):
            out.append(f"#define {n} 0x{v:03X}\n")
        out.append("\n")
        for n, v in sorted(self.hidden.items(), key=lambda kv: kv[1]):
            out.append(f"#define {n} (FLAG_HIDDEN_ITEMS_START + {v})\n")
        out.append("\n")
        for n, v in sorted(self.vars.items(), key=lambda kv: kv[1]):
            out.append(f"#define {n} 0x{v:04X}\n")
        out.append("\n#endif\n")
        write(f"{FR}/include/constants/hx_flags.h", "".join(out))


_free_vars = None


def free_vars():
    global _free_vars
    if _free_vars is None:
        txt = read(f"{FR}/include/constants/vars.h")
        cands = [int(v, 16) for n, v in re.findall(r"#define (VAR_0x[0-9A-F]+)\s+(0x[0-9A-F]+)", txt)]
        tok = collections.Counter()
        for root in ["data", "src", "include"]:
            for dp, _, fs in os.walk(os.path.join(FR, root)):
                for f in fs:
                    if not f.endswith((".json", ".inc", ".c", ".h", ".s", ".txt")):
                        continue
                    p = os.path.join(dp, f)
                    if p.endswith("constants/vars.h"):
                        continue
                    for m in re.findall(r"VAR_0x[0-9A-F]+", read(p)):
                        tok[m] += 1
        _free_vars = [c for c in cands if tok[f"VAR_0x{c:04X}"] == 0 and 0x4000 <= c < 0x4100]
    return _free_vars


# ----------------------------------------------------------------------------
# Emerald script parsing
# ----------------------------------------------------------------------------
LABEL_RE = re.compile(r"^([A-Za-z_]\w*)::?\s*(?:@.*)?$")


def parse_blocks(path):
    blocks = collections.OrderedDict()
    cur = None
    for line in read(path).split("\n"):
        m = LABEL_RE.match(line)
        if m:
            cur = m.group(1)
            blocks[cur] = []
            continue
        if cur is not None:
            blocks[cur].append(line)
    return blocks


def is_text_block(lines):
    body = [l for l in lines if l.strip()]
    return bool(body) and all(l.strip().startswith(".string") for l in body)


MOVEMENT_WORDS = re.compile(r"^(walk|face|run|jump|delay|step_end|emote|slide|ride|nurse_joy|levitate|"
                            r"set_invisible|set_visible|lock_facing|unlock_facing|player_|disable_|enable_|"
                            r"fly|acro|store_|restore_|figure|exclamation|question|heart|glide|"
                            r"walk_in_place|init_affine|clear_|jump_in_place|face_original|"
                            r"fast_|faster|fastest|slow|spin|rock|raise|flip|mirror)")


def is_movement_block(lines):
    body = [l.strip() for l in lines if l.strip() and not l.strip().startswith("@")]
    if not body:
        return False
    if not any(l.startswith("step_end") for l in body):
        return False
    return all(MOVEMENT_WORDS.match(l.split()[0]) for l in body)


def strip_comment(line):
    # remove '@' comments outside of quotes
    out = []
    inq = False
    for ch in line:
        if ch == '"':
            inq = not inq
        if ch == "@" and not inq:
            break
        out.append(ch)
    return "".join(out).rstrip()


def split_cmd(line):
    s = strip_comment(line).strip()
    if not s:
        return None, []
    parts = s.split(None, 1)
    cmd = parts[0]
    args = []
    if len(parts) > 1:
        args = [a.strip() for a in parts[1].split(",")]
    return cmd, args
