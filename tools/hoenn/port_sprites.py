#!/usr/bin/env python3
"""Import Emerald overworld sprites (object event graphics) into the FireRed tree.

usage: port_sprites.py OBJ_EVENT_GFX_FOO [OBJ_EVENT_GFX_BAR ...]
       port_sprites.py --list file.txt

State lives in tools/hoenn/sprites_db.json (so ids are stable between runs).
Generates:
  graphics/object_events/pics/hx/*.png                (copied from Emerald)
  hoenn_rules.mk                                      (gbagfx rules, one per sheet)
  src/data/object_events/hx_graphics.h                (pics, pic tables, infos)
  src/data/object_events/hx_graphics_pointers.h       (pointer table entries)
  include/constants/hx_event_objects.h                (OBJ_EVENT_GFX_HX_* ids)
"""
import json, os, re, shutil, sys

FR = os.environ.get("FR", "/home/claude/pokefirered")
EM = os.environ.get("EM", "/home/claude/pokeemerald")
DB_PATH = os.path.join(FR, "tools/hoenn/sprites_db.json")
FIRST_ID = 152
MAX_ID = 239

def read(p):
    with open(p) as f:
        return f.read()

OBJ = os.path.join(EM, "src/data/object_events")
infos_txt = read(f"{OBJ}/object_event_graphics_info.h")
ptrs_txt = read(f"{OBJ}/object_event_graphics_info_pointers.h")
pics_txt = read(f"{OBJ}/object_event_pic_tables.h")
gfx_txt = read(f"{OBJ}/object_event_graphics.h")

info_re = re.compile(r"const struct ObjectEventGraphicsInfo (gObjectEventGraphicsInfo_\w+) = \{(.*?)\n\};", re.S)
INFOS = {m.group(1): m.group(2) for m in info_re.finditer(infos_txt)}
PTRS = dict(re.findall(r"\[(OBJ_EVENT_GFX_\w+)\]\s*=\s*&(gObjectEventGraphicsInfo_\w+)", ptrs_txt))
pic_re = re.compile(r"static const struct SpriteFrameImage (sPicTable_\w+)\[\] = \{(.*?)\n\};", re.S)
PICTABLES = {m.group(1): m.group(2) for m in pic_re.finditer(pics_txt)}
GFXDEF = {}
for m in re.finditer(r'const u(?:32|16) (gObjectEventPic_\w+)\[\] = INCGFX_U32\("([^"]+)",\s*"([^"]+)"(?:,\s*"([^"]*)")?\)', gfx_txt):
    GFXDEF[m.group(1)] = (m.group(2), m.group(4) or "")

PAL_MAP = {
    "OBJ_EVENT_PAL_TAG_NPC_1": "OBJ_EVENT_PAL_TAG_HX_NPC_1",
    "OBJ_EVENT_PAL_TAG_NPC_2": "OBJ_EVENT_PAL_TAG_HX_NPC_2",
    "OBJ_EVENT_PAL_TAG_NPC_3": "OBJ_EVENT_PAL_TAG_HX_NPC_3",
    "OBJ_EVENT_PAL_TAG_NPC_4": "OBJ_EVENT_PAL_TAG_HX_NPC_4",
    "OBJ_EVENT_PAL_TAG_NONE": "OBJ_EVENT_PAL_TAG_NONE",
}
OAM_MAP = {
    "sOamTables_16x16": "gObjectEventSpriteOamTables_16x16",
    "sOamTables_16x32": "gObjectEventSpriteOamTables_16x32",
    "sOamTables_32x32": "gObjectEventSpriteOamTables_32x32",
    "sOamTables_48x48": "gObjectEventSpriteOamTables_48x48",
    "sOamTables_64x32": "gObjectEventSpriteOamTables_64x32",
    "sOamTables_64x64": "gObjectEventSpriteOamTables_64x64",
    "sOamTables_88x32": "gObjectEventSpriteOamTables_88x32",
    "sOamTables_96x40": "gObjectEventSpriteOamTables_96x40",
}
OKAY_ANIMS = {"sAnimTable_Standard", "sAnimTable_Inanimate", "sAnimTable_Nurse", "sAnimTable_AcroBike", "sAnimTable_CutTree", "sAnimTable_RockSmashRock"}

def camel(name):
    return "".join(p.capitalize() for p in name.lower().split("_"))

def load_db():
    if os.path.exists(DB_PATH):
        return json.load(open(DB_PATH))
    return {"next_id": FIRST_ID, "sprites": {}}

def field(body, name):
    m = re.search(r"\." + name + r"\s*=\s*([^,]+),", body)
    return m.group(1).strip() if m else None

def import_one(gfx, db):
    if gfx in db["sprites"]:
        return
    if gfx not in PTRS:
        raise SystemExit(f"unknown Emerald graphics id {gfx}")
    info_sym = PTRS[gfx]
    body = INFOS[info_sym]
    suffix = info_sym[len("gObjectEventGraphicsInfo_"):]
    anims = field(body, "anims")
    if anims == "sAnimTable_BreakableRock":
        body = body.replace("sAnimTable_BreakableRock", "sAnimTable_RockSmashRock")
        anims = "sAnimTable_RockSmashRock"
    if anims not in OKAY_ANIMS:
        print(f"  WARNING {gfx}: unsupported anim table {anims}", file=sys.stderr)
    pic_table = field(body, "images")
    pt_body = PICTABLES[pic_table]
    pic_syms = sorted(set(re.findall(r"gObjectEventPic_\w+", pt_body)))
    new_id = db["next_id"]
    if new_id > MAX_ID:
        raise SystemExit("out of object graphics ids")
    db["next_id"] += 1
    db["sprites"][gfx] = {
        "id": new_id, "suffix": suffix, "info_body": body, "pic_table": pic_table,
        "pic_table_body": pt_body, "pics": pic_syms,
        "pic_defs": {s: GFXDEF[s] for s in pic_syms},
    }

def build(db):
    os.makedirs(f"{FR}/graphics/object_events/pics/hx", exist_ok=True)
    pics_done = {}
    out = ["// Auto-generated by tools/hoenn/port_sprites.py -- do not edit\n"]
    out_ptr = []
    consts = []
    rules = ["# Auto-generated by tools/hoenn/port_sprites.py -- do not edit\n",
             "HXGFXDIR := graphics/object_events/pics/hx\n\n"]
    # pics
    for gfx, s in sorted(db["sprites"].items(), key=lambda kv: kv[1]["id"]):
        for sym, (path, opts) in s["pic_defs"].items():
            new_sym = sym.replace("gObjectEventPic_", "gObjectEventPic_Hx")
            if new_sym in pics_done:
                continue
            stem = os.path.splitext(os.path.basename(path))[0]
            png_dst = f"graphics/object_events/pics/hx/{stem}.png"
            shutil.copyfile(os.path.join(EM, path), os.path.join(FR, png_dst))
            if png_dst.endswith(".png"):
                rule_target = f"$(HXGFXDIR)/{stem}.4bpp"
                m = re.search(r"-mwidth (\d+) -mheight (\d+)", opts)
                extra = f" -mwidth {m.group(1)} -mheight {m.group(2)}" if m else ""
                rules.append(f"{rule_target}: %.4bpp: %.png\n\t$(GFX) $< $@{extra}\n\n")
            pics_done[new_sym] = stem
            out.append(f'const u32 {new_sym}[] = INCBIN_U32("graphics/object_events/pics/hx/{stem}.4bpp");\n')
    out.append("\n")
    # pic tables
    for gfx, s in sorted(db["sprites"].items(), key=lambda kv: kv[1]["id"]):
        body = s["pic_table_body"]
        body = body.replace("gObjectEventPic_", "gObjectEventPic_Hx")
        out.append(f"static const struct SpriteFrameImage sPicTable_Hx{s['suffix']}[] = {{{body}\n}};\n\n")
    # infos
    for gfx, s in sorted(db["sprites"].items(), key=lambda kv: kv[1]["id"]):
        b = s["info_body"].replace("sAnimTable_BreakableRock", "sAnimTable_RockSmashRock")
        for k, v in PAL_MAP.items():
            b = re.sub(r"\b" + k + r"\b", v, b)
        for k, v in OAM_MAP.items():
            b = re.sub(r"\b" + k + r"\b", v, b)
        b = re.sub(r"\.images\s*=\s*\w+", f".images = sPicTable_Hx{s['suffix']}", b)
        out.append(f"const struct ObjectEventGraphicsInfo gObjectEventGraphicsInfo_Hx{s['suffix']} = {{{b}\n}};\n\n")
        cname = "OBJ_EVENT_GFX_HX_" + gfx[len("OBJ_EVENT_GFX_"):]
        consts.append((cname, s["id"]))
        out_ptr.append(f"    [{cname}] = &gObjectEventGraphicsInfo_Hx{s['suffix']},\n")
    with open(f"{FR}/src/data/object_events/hx_graphics.h", "w") as f:
        f.writelines(out)
    with open(f"{FR}/src/data/object_events/hx_graphics_pointers.h", "w") as f:
        f.writelines(out_ptr)
    with open(f"{FR}/src/data/object_events/hx_graphics_externs.h", "w") as f:
        for gfx, s in sorted(db["sprites"].items(), key=lambda kv: kv[1]["id"]):
            f.write(f"extern const struct ObjectEventGraphicsInfo gObjectEventGraphicsInfo_Hx{s['suffix']};\n")
    last = max(i for _, i in consts) if consts else FIRST_ID - 1
    with open(f"{FR}/include/constants/hx_event_objects.h", "w") as f:
        f.write("// Auto-generated by tools/hoenn/port_sprites.py -- do not edit\n")
        f.write("#ifndef GUARD_CONSTANTS_HX_EVENT_OBJECTS_H\n#define GUARD_CONSTANTS_HX_EVENT_OBJECTS_H\n\n")
        for n, i in consts:
            f.write(f"#define {n} {i}\n")
        f.write(f"\n#define OBJ_EVENT_GFX_HX_COUNT {last + 1}\n\n#endif\n")
    with open(f"{FR}/hoenn_rules.mk", "w") as f:
        f.writelines(rules)

def main():
    args = sys.argv[1:]
    db = load_db()
    names = []
    while args:
        a = args.pop(0)
        if a == "--list":
            names += [l.strip() for l in open(args.pop(0)) if l.strip() and not l.startswith("#")]
        else:
            names.append(a)
    for n in names:
        if not n.startswith("OBJ_EVENT_GFX_"):
            n = "OBJ_EVENT_GFX_" + n
        import_one(n, db)
    json.dump(db, open(DB_PATH, "w"), indent=1)
    build(db)
    print(f"{len(db['sprites'])} sprites imported; next id {db['next_id']}")

if __name__ == "__main__":
    main()
