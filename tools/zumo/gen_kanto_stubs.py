#!/usr/bin/env python3
"""Zumo: generate placeholder scripts for Kanto (FRLG) maps in the Emerald build.

The FRLG story scripts are not compiled into the Emerald build (their flags/vars
overlap Hoenn's). Every script label that a Kanto map.json references but that
no compiled script file defines gets an empty stub, so the maps can be loaded and
walked around. As real Zumo scripts get written, rerun this and the stubs shrink.

Run from the repo root:  python3 tools/zumo/gen_kanto_stubs.py
"""
import glob, json, re

OUT = 'data/maps/zumo_kanto_stubs.inc'

es = open('data/event_scripts.s').read()
a = es.index('.if IS_FRLG')
b = es.index('.endif', a)
frlg_only = set(re.findall(r'\.include "([^"]+)"', es[a:b]))

defined = set()
for f in set(glob.glob('data/**/*.inc', recursive=True)) | set(glob.glob('data/*.s')):
    if f in frlg_only or f == OUT or re.search(r'data/maps/\w+_Frlg/', f):
        continue
    for m in re.finditer(r'^(\w+)::?', open(f, errors='ignore').read(), re.M):
        defined.add(m.group(1))

map_scripts, event_scripts = [], []
seen = set()
for f in sorted(glob.glob('data/maps/*/map.json')):
    j = json.load(open(f))
    if j.get('region') != 'REGION_KANTO':
        continue
    if not j.get('shared_scripts_map'):
        l = j['name'] + '_MapScripts'
        if l not in defined and l not in seen:
            seen.add(l); map_scripts.append(l)
    for key in ('object_events', 'coord_events', 'bg_events'):
        for ev in j.get(key) or []:
            l = ev.get('script')
            if l and l not in ('0', 'NULL') and l not in defined and l not in seen:
                seen.add(l); event_scripts.append(l)

with open(OUT, 'w') as o:
    o.write('@ AUTO-GENERATED by tools/zumo/gen_kanto_stubs.py -- do not edit by hand.\n')
    o.write('@ Placeholder scripts for Kanto maps until the Zumo story scripts replace them.\n\n')
    for l in map_scripts:
        o.write(f'{l}::\n\t.byte 0\n\n')
    for l in event_scripts:
        o.write(f'{l}::\n\tend\n\n')
print(f'{len(map_scripts)} map script stubs, {len(event_scripts)} event script stubs -> {OUT}')
